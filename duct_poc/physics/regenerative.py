"""Flow-generated (regenerative / self-noise) sound power from duct fittings.

Each fitting (elbow, takeoff, damper, diffuser) produces sound power whose
level depends primarily on local flow velocity and a characteristic area.
ASHRAE uses empirical forms of the shape:

    L_W(f) = K_1(f) + 10 log10(V^n) + 10 log10(A) + constants

where V is velocity and A is a characteristic area. We use a simplified
generic PoC form with a band shape and a velocity exponent n=5 (strong
V dependence, matching the ASHRAE formula for high-velocity fittings).

All parameters smooth: velocity in m/s, area in m^2. Output: (8,) PWL in dB.
"""
from __future__ import annotations

import torch

# Typical band shape (K_1) for a generic fitting, normalised to peak at 250 Hz.
# Representative of a 90-degree bend or takeoff; differs from an FCU (which
# is broader and louder) — but we only need a shape for the demo.
K1_BAND = torch.tensor(
    # 63    125   250   500   1k    2k    4k    8k
    [-8.0, -4.0, 0.0, -3.0, -7.0, -12.0, -18.0, -24.0],
    dtype=torch.float64,
)

# Reference: V=1 m/s, A=1 m^2 gives approximately a broadband PWL ~50 dB
# at 250 Hz for a generic fitting. Offset to get into the right range.
PWL_OFFSET_DB = 50.0


def regenerative_pwl_db(
    velocity_mps: torch.Tensor,
    area_m2: torch.Tensor,
    strength_db: torch.Tensor | None = None,
) -> torch.Tensor:
    """Sound-power level per octave band generated by a fitting.

    Args:
        velocity_mps: flow velocity at the fitting (m/s, scalar tensor)
        area_m2: characteristic cross-section area (scalar tensor)
        strength_db: optional extra gain to distinguish bend/takeoff/damper
                     character; None means 0 dB (generic fitting).
    Returns:
        (8,) tensor of PWL in dB.
    """
    v = torch.clamp(velocity_mps, min=0.1)
    a = torch.clamp(area_m2, min=1e-4)
    pwl_broadband = (
        50.0 * torch.log10(v)  # V^5 dependence (strong)
        + 10.0 * torch.log10(a)
        + PWL_OFFSET_DB
    )
    extra = strength_db if strength_db is not None else torch.tensor(0.0, dtype=v.dtype)
    return pwl_broadband + K1_BAND + extra
