//! Flow-generated (regenerative / self-noise) sound power.
//!
//! Fittings (bends, tees, dampers), by Woods' method as Arup's Strutt
//! documents it, `K` the fitting's datum level:
//! ```text
//!     L_W = K + 10 log10(S) + 55 log10(V) − 45,  less a band correction
//! ```
//! or, where the fitting's pressure loss factor `ζ` is known, CIBSE Guide B
//! (2005) 5.A2.4's detailed method (equations 5.A2.5 to 5.A2.11), `σ = 1 / (√ζ + 1)` the
//! clear area ratio, `v_c = u / σ`, `d = b (1 − σ)` for `b` the duct across
//! the constriction, `St = f d / v_c`:
//! ```text
//!     L_W = −37 + 20 lg K(St) + 20 lg ζ + 10 lg A + 40 lg u               f < f_c
//!     L_W = −84 + 20 lg K(St) + 20 lg St + 10 lg ζ − 40 lg σ + 10 lg A + 60 lg u
//! ```
//! `f_c = c / 2l` the cut-on of the duct's longest side `l`.
//!
//! Junctions (tees, take-offs), by ASHRAE's *Algorithms for HVAC Acoustics*
//! (Reynolds and Bledsoe, 1991), as Yayladere's METU thesis gives it (eq. 3.3 to
//! 3.10; we have not seen the handbook, and its units are read from eq. 3.4, 3.6),
//! `U` in ft/s, `S` in ft², `D` in ft, `m = U_M / U_B`, `St = f D_B / U_B`:
//! ```text
//!     L_W = K_J + 10 lg(f / 63) + 50 lg U_B + 10 lg S_B + 10 lg D_B + Δr + ΔT
//!     K_J = −21.61 + 12.388 m^0.673 − 16.482 m^−0.303 lg St − 5.047 m^−0.254 (lg St)²
//!     Δr  = 6.793 − 1.86 lg St                    a sharp inside edge
//!     ΔT  = −1.667 + 1.8 m − 0.133 m²             turbulence within 5 main diameters
//! ```
//! The fit gives no range for `m`. With the main's speed fixed its level falls
//! to about `m = 5` and then climbs, 118 dB by `m = 50` from a branch barely
//! moving, so `m` is held at [`JUNCTION_M_MAX`] (our limit, not the source's).
//!
//! Terminals (diffusers, grilles), by CIBSE Guide B (2005) 5.A2.5: a peak at
//! `f = 160 u` falling 3 dB per octave below and 5 above,
//! ```text
//!     L_W(peak) = 10 + 10 log10(A) + 30 log10(Δp)
//! ```
//! A silencer's own noise is left out: TM 5-805-4 finds it "seldom a
//! problem" below about 15 m/s.

use crate::autodiff::Dual;

use crate::metrics::octave::{N_BANDS, OCTAVE_BANDS_HZ};

/// Woods' octave band corrections to a fitting's total, 63 Hz to 8 kHz.
const WOODS_BAND: [f64; N_BANDS] = [-6.0, -6.0, -7.0, -7.0, -8.0, -10.0, -17.0, -29.0];

/// CIBSE Guide B fig. 5.A2.3 (±2 dB), read off: 20 lg K is 75 dB to St = 1
/// (the plateau example 5.A2.1 reads), then falls straight in log St to
/// 12.5 dB at St = 200; beyond, the line is carried on.
const K_PLATEAU_DB: f64 = 75.0;
const K_AT_200_DB: f64 = 12.5;
const C_AIR: f64 = 343.0;

/// A ceiling diffuser's pressure loss factor, Δp = ζ ρ u² / 2: about 20 Pa
/// at a 3 m/s neck. Catalogue data would replace it.
const DIFFUSER_ZETA: f64 = 4.0;
const RHO_AIR: f64 = 1.2;

/// PWL per octave band generated by a fitting of datum level `k_db` (Woods'
/// table 5.2: open damper 44, radiused bend 48, tee 55, vaned mitre 56,
/// mitre 57), velocity and area.
pub fn fitting_pwl_db<const N: usize>(k_db: Dual<N>, velocity_mps: Dual<N>, area_m2: Dual<N>) -> [Dual<N>; N_BANDS] {
    let v = velocity_mps.max_f(0.1);
    let total = k_db + area_m2.max_f(1e-4).log10() * 10.0 + v.log10() * 55.0 - 45.0;
    WOODS_BAND.map(|c| total + c)
}

fn k_st_db<const N: usize>(st: Dual<N>) -> Dual<N> {
    if st.value <= 1.0 {
        Dual::constant(K_PLATEAU_DB)
    } else {
        Dual::constant(K_PLATEAU_DB) - st.log10() * ((K_PLATEAU_DB - K_AT_200_DB) / 200f64.log10())
    }
}

/// PWL per octave band generated by a fitting of pressure loss factor `zeta`
/// (CIBSE's detailed method), velocity and area, `across_m` the duct across
/// the constriction (a bend's width in its plane) and `longest_m` its longest
/// side.
pub fn cibse_fitting_pwl_db<const N: usize>(
    zeta: f64,
    velocity_mps: Dual<N>,
    area_m2: Dual<N>,
    across_m: Dual<N>,
    longest_m: Dual<N>,
) -> [Dual<N>; N_BANDS] {
    let zeta = zeta.max(1e-3);
    let sigma = 1.0 / (zeta.sqrt() + 1.0);
    let u = velocity_mps.max_f(0.1);
    let d = across_m * (1.0 - sigma);
    let f_c = Dual::<N>::constant(C_AIR) / (longest_m * 2.0);
    let area_db = area_m2.max_f(1e-4).log10() * 10.0;
    OCTAVE_BANDS_HZ.map(|f| {
        let st = d * f * sigma / u;
        let k = k_st_db(st);
        if f < f_c.value {
            k + area_db + u.log10() * 40.0 + (20.0 * zeta.log10() - 37.0)
        } else {
            k + st.log10() * 20.0 + area_db + u.log10() * 60.0 + (10.0 * zeta.log10() - 40.0 * sigma.log10() - 84.0)
        }
    })
}

/// The most of `m = U_M / U_B` the junction fit is taken to: its level's least,
/// the main's speed fixed. Not from the source.
pub const JUNCTION_M_MAX: f64 = 5.0;
const M_PER_FT: f64 = 0.3048;

/// PWL per octave band generated in a branch of `branch_speed_mps` and
/// `branch_area_m2` by the junction it leaves a main of `main_speed_mps` at,
/// with a sharp inside edge; `turbulent` where a damper, elbow or take-off
/// lies within 5 main diameters upstream.
pub fn junction_pwl_db<const N: usize>(main_speed_mps: Dual<N>, branch_speed_mps: Dual<N>, branch_area_m2: Dual<N>, turbulent: bool) -> [Dual<N>; N_BANDS] {
    let u_b = branch_speed_mps.max_f(0.1);
    let s_b = branch_area_m2.max_f(1e-4);
    let d_b = (s_b * (4.0 / std::f64::consts::PI)).sqrt();
    let m = (main_speed_mps.max_f(0.1) / u_b).clamp_f(0.1, JUNCTION_M_MAX);
    let pow = |e: f64| (m.ln() * e).exp();
    let delta_t = if turbulent { m * 1.8 - m * m * 0.133 - 1.667 } else { Dual::constant(0.0) };
    let size_db = (u_b / M_PER_FT).log10() * 50.0 + (s_b / (M_PER_FT * M_PER_FT)).log10() * 10.0 + (d_b / M_PER_FT).log10() * 10.0;
    OCTAVE_BANDS_HZ.map(|f| {
        let lg_st = (d_b * f / u_b).log10();
        let k_j = pow(0.673) * 12.388 - pow(-0.303) * lg_st * 16.482 - pow(-0.254) * lg_st * lg_st * 5.047 - 21.61;
        k_j + 10.0 * (f / 63.0).log10() + size_db + (lg_st * -1.86 + 6.793) + delta_t
    })
}

/// PWL per octave band generated by a diffuser of neck velocity and area.
pub fn terminal_pwl_db<const N: usize>(velocity_mps: Dual<N>, area_m2: Dual<N>) -> [Dual<N>; N_BANDS] {
    let u = velocity_mps.max_f(0.1);
    let dp = u * u * (DIFFUSER_ZETA * RHO_AIR / 2.0);
    let peak = area_m2.max_f(1e-4).log10() * 10.0 + dp.log10() * 30.0 + 10.0;
    let f_peak = u * 160.0;
    let mut out = [Dual::<N>::constant(0.0); N_BANDS];
    for i in 0..N_BANDS {
        // Octaves above the peak; negative below it.
        let octaves = (Dual::<N>::constant(OCTAVE_BANDS_HZ[i]) / f_peak).log2();
        out[i] = if octaves.value < 0.0 { peak + octaves * 3.0 } else { peak - octaves * 5.0 };
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use approx::assert_relative_eq;

    /// A mitred bend, 0.5 m² at 10 m/s: 57 − 3.01 + 55 − 45 = 63.99 dB in
    /// all, 57.99 at 63 Hz.
    #[test]
    fn woods_mitred_bend() {
        let c = Dual::<1>::constant;
        let lw = fitting_pwl_db(c(57.0), c(10.0), c(0.5));
        assert_relative_eq!(lw[0].value, 57.99, epsilon = 0.01);
    }

    /// Doubling velocity adds 16.56 dB (= 55 log10 2) at every band.
    #[test]
    fn fitting_doubling_velocity() {
        let c = Dual::<1>::constant;
        let (lo, hi) = (fitting_pwl_db(c(50.0), c(4.0), c(0.1)), fitting_pwl_db(c(50.0), c(8.0), c(0.1)));
        for i in 0..N_BANDS {
            assert_relative_eq!(hi[i].value - lo[i].value, 55.0 * 2f64.log10(), max_relative = 1e-12);
        }
    }

    /// A 200 x 200 mm branch at 3 m/s off a main at 8 m/s, m = 2.667, at 1 kHz,
    /// term by term from the published equations.
    #[test]
    fn ashrae_junction_by_hand() {
        let c = Dual::<1>::constant;
        let (m, u_b, s, d): (f64, f64, f64, f64) = (8.0 / 3.0, 3.0, 0.04, (0.16 / std::f64::consts::PI).sqrt());
        let lg_st = (1000.0 * d / u_b).log10();
        let k_j = -21.61 + 12.388 * m.powf(0.673) - 16.482 * m.powf(-0.303) * lg_st - 5.047 * m.powf(-0.254) * lg_st * lg_st;
        let by_hand = k_j + 10.0 * (1000.0f64 / 63.0).log10() + 50.0 * (u_b / 0.3048).log10() + 10.0 * (s / (0.3048 * 0.3048)).log10() + 10.0 * (d / 0.3048).log10() + 6.793 - 1.86 * lg_st;
        assert_relative_eq!(junction_pwl_db(c(8.0), c(3.0), c(0.04), false)[4].value, by_hand, epsilon = 1e-9);
        // ΔT at m = 2.667: −1.667 + 4.8 − 0.946.
        let turbulent = junction_pwl_db(c(8.0), c(3.0), c(0.04), true)[4].value;
        assert_relative_eq!(turbulent - by_hand, 2.187, epsilon = 0.001);
    }

    /// Past the cap, a slower branch only gets quieter: the fit alone reads
    /// over 100 dB at 50 to 1.
    #[test]
    fn junction_quietens_as_the_branch_slows() {
        let c = Dual::<1>::constant;
        let at = |u_b: f64| junction_pwl_db(c(8.0), c(u_b), c(0.04), false);
        for pair in [1.6, 0.8, 0.4, 0.16].windows(2) {
            let (fast, slow) = (at(pair[0]), at(pair[1]));
            assert!((0..N_BANDS).all(|i| slow[i].value < fast[i].value));
        }
        assert!(at(0.16)[0].value < 40.0);
    }

    /// CIBSE Guide B example 5.A2.1: 600 x 400 mm, the 400 across the
    /// constriction, ζ = 1.25, 15 m/s. Below cut-on (286 Hz), at 125 Hz,
    /// −37 + 75 + 2 − 6 + 47 = 81 dB; above, at 1 kHz (St 6.6, 20 lg K 53),
    /// −84 + 53 + 16 + 1 + 13 − 6 + 71 = 64 dB, each term rounded; unrounded
    /// 80.8 and 63.5.
    #[test]
    fn cibse_guide_b_example() {
        let c = Dual::<1>::constant;
        let lw = cibse_fitting_pwl_db(1.25, c(15.0), c(0.24), c(0.4), c(0.6));
        assert_relative_eq!(lw[1].value, 81.0, epsilon = 0.5);
        assert_relative_eq!(lw[4].value, 64.0, epsilon = 0.6);
    }

    /// A mitred bend, ζ = 1.2, 0.7 m square at 10 m/s: σ = 0.4772,
    /// v_c = 20.95 m/s, d = 0.3660 m, f_c = 245 Hz. At 125 Hz St = 2.183,
    /// 20 lg K = 75 − 27.16 lg 2.183 = 65.79, L_W = −37 + 65.79 + 1.58
    /// − 3.10 + 40 = 67.27 dB; at 1 kHz St = 17.47, 20 lg K = 41.26,
    /// L_W = −84 + 41.26 + 24.85 + 0.79 + 12.85 − 3.10 + 60 = 52.65 dB.
    #[test]
    fn cibse_mitred_bend() {
        let c = Dual::<1>::constant;
        let lw = cibse_fitting_pwl_db(1.2, c(10.0), c(0.49), c(0.7), c(0.7));
        assert_relative_eq!(lw[1].value, 67.27, epsilon = 0.02);
        assert_relative_eq!(lw[4].value, 52.65, epsilon = 0.02);
    }

    /// The figure, read back: the plateau to St = 1, 40 dB at St = 20, and
    /// example 5.A2.1's 53 dB at St = 6.6.
    #[test]
    fn k_of_strouhal() {
        let c = Dual::<1>::constant;
        assert_relative_eq!(k_st_db(c(0.3)).value, 75.0);
        assert_relative_eq!(k_st_db(c(20.0)).value, 40.0, epsilon = 0.5);
        assert_relative_eq!(k_st_db(c(6.6)).value, 53.0, epsilon = 0.5);
        assert_relative_eq!(k_st_db(c(200.0)).value, 12.5, max_relative = 1e-12);
    }

    /// A 0.1 m² diffuser at 3.125 m/s: Δp = 4 · 0.6 · 9.77 = 23.4 Pa, peak
    /// 10 − 10 + 41.1 = 41.1 dB at 500 Hz, 38.1 at 250 and 36.1 at 1 kHz.
    #[test]
    fn cibse_terminal_spectrum() {
        let c = Dual::<1>::constant;
        let lw = terminal_pwl_db(c(3.125), c(0.1));
        let peak = 10.0 - 10.0 + 30.0 * (2.4f64 * 3.125 * 3.125).log10();
        assert_relative_eq!(lw[3].value, peak, max_relative = 1e-12);
        assert_relative_eq!(lw[2].value, peak - 3.0, max_relative = 1e-12);
        assert_relative_eq!(lw[4].value, peak - 5.0, max_relative = 1e-12);
    }
}
